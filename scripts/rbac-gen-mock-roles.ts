/**
 * Regenerates lib/mocks/routes/rbac-roles.generated.ts from the backend's seeded roles
 * and permission pool (names and descriptions).
 * Run: npx tsx scripts/rbac-gen-mock-roles.ts
 *
 * Mock mode signs in as a super admin, so no role-based behaviour can be tried in
 * the browser. The mock login (lib/mocks/routes/auth.ts) therefore also accepts
 * `<role>@abode.ng` and `<role>+<role>@abode.ng` for any seeded role, and builds
 * the session from this file. The file is copied from the backend seed rather
 * than written by hand, so the mock roles cannot drift from the real ones.
 *
 * Needs the backend source: ABODE_BE_V2_PATH, or the sibling default
 * (../../Abode-Combine/Abode-Backend/abode-be-v2 from this repo).
 */
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

const REPO = path.resolve(__dirname, '..');
const BE_ROOT = path.resolve(
  process.env.ABODE_BE_V2_PATH ?? path.join(REPO, '..', '..', 'Abode-Combine', 'Abode-Backend', 'abode-be-v2'),
  'src',
);

function load<T>(file: string, permissionsModule?: unknown): T {
  const src = fs.readFileSync(file, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
  const mod = { exports: {} as Record<string, unknown> };
  new Function('module', 'exports', 'require', out)(mod, mod.exports, (id: string) => {
    if (id.endsWith('/permissions') && permissionsModule) return permissionsModule;
    throw new Error(`unexpected require("${id}") in ${file}`);
  });
  return mod.exports as T;
}

type Seeded = { name: string; description: string; permissions: string[]; is_super_admin: boolean; default_landing_page?: string };
type Pool = { PERMISSIONS: string[]; PERMISSION_DESCRIPTIONS: Record<string, string> };

if (!fs.existsSync(path.join(BE_ROOT, 'common', 'permissions.ts'))) {
  console.error(`Backend source not found at ${BE_ROOT}. Set ABODE_BE_V2_PATH.`);
  process.exit(1);
}

const perms = load<Pool & Record<string, unknown>>(path.join(BE_ROOT, 'common', 'permissions.ts'));
const seed = load<{ DEFAULT_ROLES: Seeded[] }>(path.join(BE_ROOT, 'modules', 'role', 'role.seed.ts'), perms);

const roles = seed.DEFAULT_ROLES.map((role) => ({
  name: role.name,
  description: role.description,
  is_super_admin: role.is_super_admin,
  default_landing_page: role.default_landing_page ?? 'dashboard',
  // A super-admin role resolves to the whole pool at runtime, so its stored list is not copied.
  permissions: role.is_super_admin ? [] : [...new Set(role.permissions)],
}));

const lines = roles.map(
  (role) =>
    `  ${role.name}: {\n    description: ${JSON.stringify(role.description)},\n    is_super_admin: ${role.is_super_admin},\n    default_landing_page: '${role.default_landing_page}',\n    permissions: [\n${role.permissions.map((p) => `      '${p}',`).join('\n')}\n    ],\n  },`,
);

const out = `/* eslint-disable */
// GENERATED by scripts/rbac-gen-mock-roles.ts from abode-be-v2 role.seed.ts. Do not edit by hand:
// run \`npx tsx scripts/rbac-gen-mock-roles.ts\` after the backend seed changes.

export type MockSeededRole = {
  description: string;
  is_super_admin: boolean;
  default_landing_page: string;
  permissions: string[];
};

export const MOCK_SEEDED_ROLES: Record<string, MockSeededRole> = {
${lines.join('\n')}
};

/** The whole permission pool with its description, as GET /admin/permissions returns it. */
export const MOCK_PERMISSION_POOL: Array<{ name: string; description: string }> = [
${perms.PERMISSIONS.map((name) => `  { name: '${name}', description: ${JSON.stringify(perms.PERMISSION_DESCRIPTIONS[name] ?? '')} },`).join('\n')}
];
`;

const target = path.join(REPO, 'lib', 'mocks', 'routes', 'rbac-roles.generated.ts');
fs.writeFileSync(target, out.replace(/\n/g, '\r\n'));
console.log(`wrote ${path.relative(REPO, target)}: ${roles.length} roles`);
